import type { Core } from '@strapi/strapi';

const allowedMediaTypes = [
  'image/*',
  'video/*',
  'audio/*',
  'application/pdf',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.*',
  'text/plain',
  'text/csv',
];

const deniedExecutableTypes = [
  'application/vnd.microsoft.portable-executable',
  'application/x-msdownload',
  'application/x-msdos-program',
  'application/x-executable',
  'application/x-dosexec',
  'application/x-sh',
  'text/x-shellscript',
  'application/x-mach-binary',
];

const config = ({ env }: Core.Config.Shared.ConfigParams): Core.Config.Plugin => ({
  'users-permissions': {
    config: {
      jwtManagement: 'refresh',
      sessions: {
        httpOnly: true,
        cookie: {
          // Nur auf true setzen, wenn Strapi hinter TLS/HTTPS läuft (z. B. Reverse-Proxy).
          secure: env.bool('SESSION_COOKIE_SECURE', false),
        },
      },
    },
  },
  upload: {
    config: {
      security: {
        allowedTypes: allowedMediaTypes,
        deniedTypes: deniedExecutableTypes,
      },
    },
  },
  // Used for forgot-password emails (see ensureResetPasswordUrl in src/index.ts). Without
  // SMTP_HOST set, Strapi falls back to its no-op "sendmail" provider - forgot-password then
  // silently does nothing instead of sending an email.
  email: {
    config: {
      provider: 'nodemailer',
      providerOptions: {
        host: env('SMTP_HOST'),
        port: env.int('SMTP_PORT', 587),
        secure: env.bool('SMTP_SECURE', false),
        auth: {
          user: env('SMTP_USERNAME'),
          pass: env('SMTP_PASSWORD'),
        },
      },
      settings: {
        defaultFrom: env('SMTP_FROM', env('SMTP_USERNAME')),
        defaultReplyTo: env('SMTP_REPLY_TO', env('SMTP_USERNAME')),
      },
    },
  },
});

export default config;
